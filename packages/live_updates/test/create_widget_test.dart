import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:live_updates/src/cli/create_widget.dart';

void main() {
  for (final option in ['--name', '--ios-dir', '--app-group']) {
    test('$option without a value is a usage error', () async {
      expect(await createWidget([option]), 64);
    });
  }
  group('files', fileRules);
}

void fileRules() {
  late Directory root;
  late String ios;
  setUp(() {
    root = Directory.systemTemp.createTempSync('lu_cw_');
    ios = '${root.path}/ios';
    Directory('$ios/Runner.xcodeproj').createSync(recursive: true);
  });
  tearDown(() => root.deleteSync(recursive: true));

  Future<int> run([List<String> extra = const []]) => createWidget([
    '--ios-dir',
    ios,
    '--no-xcode',
    ...extra,
  ], templates: Directory('lib/src/cli/ios_widget'));

  File file(String name) => File('$ios/LiveUpdatesWidget/$name');

  test(
    'writes every file, then keeps yours and replaces the plugin\'s',
    () async {
      expect(await run(), 0);
      for (final f in [
        'LiveUpdatesAttributes.swift',
        'LiveUpdatesViews.swift',
        'LiveUpdatesActionIntent.swift',
        'LiveUpdatesWidgetLiveActivity.swift',
        'LiveUpdatesWidgetBundle.swift',
        'Info.plist',
      ]) {
        expect(file(f).existsSync(), isTrue, reason: f);
      }
      file('LiveUpdatesWidgetLiveActivity.swift').writeAsStringSync('// mine');
      file('LiveUpdatesViews.swift').writeAsStringSync('// stale generated');
      expect(await run(), 0);
      expect(
        file('LiveUpdatesWidgetLiveActivity.swift').readAsStringSync(),
        '// mine',
      );
      expect(
        file('LiveUpdatesViews.swift').readAsStringSync(),
        contains('struct LiveUpdatesLockScreen'),
      );
      // Not generated by create_widget: a copy is kept before replacing.
      expect(
        file('LiveUpdatesViews.swift.bak').readAsStringSync(),
        '// stale generated',
      );
    },
  );

  test('--force replaces your files too', () async {
    expect(await run(), 0);
    file('LiveUpdatesWidgetLiveActivity.swift').writeAsStringSync('// mine');
    expect(await run(['--force']), 0);
    expect(
      file('LiveUpdatesWidgetLiveActivity.swift').readAsStringSync(),
      contains('struct LiveUpdatesWidgetLiveActivity'),
    );
  });

  test('the attributes match the plugin source', () async {
    expect(await run(), 0);
    final plugin = File(
      'ios/live_updates/Sources/live_updates/LiveUpdatesAttributes.swift',
    ).readAsStringSync();
    expect(file('LiveUpdatesAttributes.swift').readAsStringSync(), plugin);
  });

  test('rejects names and app groups that are not valid', () async {
    expect(await run(['--name', '1bad']), 64);
    expect(await run(['--app-group', 'com.example']), 64);
  });

  test('needs an Xcode project', () async {
    expect(
      await createWidget(['--ios-dir', '${root.path}/none', '--no-xcode']),
      66,
    );
  });
}
