// Extracts the Dart code blocks of the package READMEs into compilable files
// so that `flutter analyze` catches examples that no longer compile.
//
// Usage, from the repository root:
//
//   dart run tool/check_readme_snippets.dart
//   flutter analyze build/readme_snippets
//
// Each ```dart block becomes one file, with the block's imports at the top:
// - a block with a top-level `main`, `@pragma` or class is a library;
// - a block that starts with `name:` is a named argument and goes inside a
//   `LiveUpdateContent(...)` call;
// - any other block is a list of statements inside an async function.
//
// Names that the examples leave to the app (`api`, `router`, `eta`, ...) are
// declared in `_stubs.dart`. A block that follows `<!-- snippet: skip -->`
// is not checked.
import 'dart:io';

const _readmes = [
  'packages/live_updates/README.md',
  'packages/live_updates_fcm/README.md',
];

/// The workspace resolves both packages here; build/ is ignored by git.
const _outDir = 'build/readme_snippets';

const _imports = '''
// GENERATED by tool/check_readme_snippets.dart. Do not edit.
// ignore_for_file: unused_local_variable, unused_import, avoid_print, unused_element, depend_on_referenced_packages, unnecessary_import, duplicate_import
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/widgets.dart';
import 'package:live_updates/live_updates.dart';
import 'package:live_updates_fcm/live_updates_fcm.dart';
''';

const _stubs = '''
// GENERATED by tool/check_readme_snippets.dart. Do not edit.
// Names the README examples leave to the app.
// ignore_for_file: type=lint
import 'package:flutter/widgets.dart';
import 'package:live_updates/live_updates.dart';

final dynamic api = Object();
final dynamic router = Object();
void track(LiveUpdate update) {}
final DateTime eta = DateTime.now();
final DateTime startedAt = DateTime.now();
const LiveUpdateContent content = LiveUpdateContent(title: '');
const String channelIdFromYourServer = '';

class App extends StatelessWidget {
  const App({super.key});

  @override
  Widget build(BuildContext context) => const SizedBox();
}
''';

const _stubsImport = "import '_stubs.dart';\n";

final _fence = RegExp(r'^(\s*)```(\w*)\s*$');
final _namedArgument = RegExp(r'^[a-zA-Z_]\w*\s*:');
final _isLibrary = RegExp(
  r'^(@pragma|Future<void> main|void main|class )',
  multiLine: true,
);

void main() {
  final out = Directory(_outDir);
  if (out.existsSync()) out.deleteSync(recursive: true);
  out.createSync(recursive: true);
  File('${out.path}/_stubs.dart').writeAsStringSync(_stubs);

  var count = 0;
  for (final readme in _readmes) {
    final package = readme.split('/')[1];
    final lines = File(readme).readAsLinesSync();
    var skipNext = false;
    for (var i = 0; i < lines.length; i++) {
      if (lines[i].trim() == '<!-- snippet: skip -->') {
        skipNext = true;
        continue;
      }
      final open = _fence.firstMatch(lines[i]);
      if (open == null) continue;
      final indent = open.group(1)!.length;
      final language = open.group(2)!;
      final start = i + 1;
      var end = start;
      while (end < lines.length && _fence.firstMatch(lines[end]) == null) {
        end++;
      }
      final code = lines
          .sublist(start, end)
          .map((l) => l.length >= indent ? l.substring(indent) : l.trimLeft())
          .join('\n');
      i = end;
      // The skip marker applies to the next block, whatever its language.
      final skip = skipNext;
      skipNext = false;
      if (language != 'dart' || skip) continue;
      final name = '${package}_line${start + 1}.dart';
      File('${out.path}/$name').writeAsStringSync(_wrap(code, readme, start));
      count++;
    }
  }
  stdout.writeln('Wrote $count README snippets to $_outDir.');
}

String _wrap(String code, String readme, int line) {
  // The example's own imports first, then the shared ones.
  final lines = code.split('\n');
  final imports = lines.where((l) => l.startsWith('import ')).join('\n');
  final body = lines.where((l) => !l.startsWith('import ')).join('\n');
  final header =
      '$imports\n$_imports$_stubsImport// $readme, line ${line + 1}\n';
  if (_isLibrary.hasMatch(body)) return '$header\n$body\n';
  final firstCode = body
      .split('\n')
      .map((l) => l.trimLeft())
      .firstWhere((l) => l.isNotEmpty && !l.startsWith('//'), orElse: () => '');
  if (_namedArgument.hasMatch(firstCode)) {
    final hasTitle = RegExp(r'^\s*title\s*:', multiLine: true).hasMatch(body);
    final title = hasTitle ? '' : "title: '',";
    return "$header\nFuture<void> snippet() async {\n"
        "  LiveUpdateContent($title\n$body\n  );\n}\n";
  }
  return '$header\nFuture<void> snippet() async {\n$body\n}\n';
}
