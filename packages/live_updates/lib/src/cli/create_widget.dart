import 'dart:io';
import 'dart:isolate';

const _usage = '''
Generates the SwiftUI Live Activity widget extension for live_updates.

Usage: dart run live_updates:create_widget [options]

Options:
  --name <Name>     Extension target name (default: LiveUpdatesWidget)
  --ios-dir <dir>   Flutter iOS directory (default: ios)
  --app-group <id>  App Group shared with the widget for images
                    (default: group.<app bundle id>)
  --no-app-group    Do not set up an App Group
  --no-xcode        Only write the widget sources; do not change
                    Runner.xcodeproj, Info.plist or entitlements
  --force           Also overwrite the files meant for you to edit
                    (<Name>LiveActivity.swift, <Name>Bundle.swift,
                    Info.plist). LiveUpdatesAttributes.swift,
                    LiveUpdatesViews.swift and LiveUpdatesActionIntent.swift
                    are always updated.
  -h, --help        Show this help
''';

/// Entry point of `dart run live_updates:create_widget`.
///
/// [templates] overrides where the templates are read from (tests run
/// without package URI resolution).
Future<int> createWidget(List<String> args, {Directory? templates}) async {
  var name = 'LiveUpdatesWidget';
  var iosDir = 'ios';
  var editXcode = true;
  var force = false;
  String? appGroup = 'auto';
  for (var i = 0; i < args.length; i++) {
    if (const {'--name', '--ios-dir', '--app-group'}.contains(args[i]) &&
        i + 1 >= args.length) {
      stderr.write('${args[i]} needs a value\n\n$_usage');
      return 64;
    }
    switch (args[i]) {
      case '--name':
        name = args[++i];
      case '--ios-dir':
        iosDir = args[++i];
      case '--app-group':
        appGroup = args[++i];
      case '--no-app-group':
        appGroup = null;
      case '--no-xcode':
        editXcode = false;
      case '--force':
        force = true;
      case '-h' || '--help':
        stdout.write(_usage);
        return 0;
      default:
        stderr.write('Unknown option ${args[i]}\n\n$_usage');
        return 64;
    }
  }
  if (!RegExp(r'^[A-Za-z][A-Za-z0-9]*$').hasMatch(name)) {
    stderr.writeln('--name must be a Swift identifier, got "$name".');
    return 64;
  }
  if (appGroup != null &&
      appGroup != 'auto' &&
      !RegExp(r'^group\.[A-Za-z0-9.-]+$').hasMatch(appGroup)) {
    stderr.writeln('--app-group must look like group.com.example.app.');
    return 64;
  }
  final ios = Directory(iosDir);
  final xcodeproj = Directory('$iosDir/Runner.xcodeproj');
  if (!xcodeproj.existsSync()) {
    stderr.writeln('${xcodeproj.path} not found. Run from your app root.');
    return 66;
  }

  if (editXcode && !_ensureXcodeprojGem()) return 69;

  templates ??= await _templatesDir();
  final dir = templates;
  String render(String file) =>
      File('${dir.path}/$file').readAsStringSync().replaceAll('{{name}}', name);

  final out = Directory('${ios.path}/$name');
  // Owned by the plugin: always replaced, so they match the plugin version.
  final owned = {
    'LiveUpdatesAttributes.swift': _attributesSource(dir),
    'LiveUpdatesViews.swift': render('Views.swift.tmpl'),
    'LiveUpdatesActionIntent.swift': render('ActionIntent.swift.tmpl'),
  };
  // Yours to edit: written once, replaced only with --force.
  final editable = {
    '${name}LiveActivity.swift': render('LiveActivityWidget.swift.tmpl'),
    '${name}Bundle.swift': render('WidgetBundle.swift.tmpl'),
    'Info.plist': render('Info.plist.tmpl'),
  };
  out.createSync(recursive: true);
  for (final MapEntry(key: file, value: content) in owned.entries) {
    final f = File('${out.path}/$file');
    if (f.existsSync()) {
      final old = f.readAsStringSync();
      if (old == content) {
        stdout.writeln('same   ${f.path}');
        continue;
      }
      // A file without the generated marker may hold your own code: keep a
      // copy. (LiveUpdatesAttributes.swift must match the plugin anyway.)
      if (file != 'LiveUpdatesAttributes.swift' &&
          !old.contains(_generatedMarker)) {
        File('${f.path}.bak').writeAsStringSync(old);
        stdout.writeln('backup ${f.path}.bak (not generated by create_widget)');
      }
    }
    f.writeAsStringSync(content);
    stdout.writeln('write  ${f.path}');
  }
  // Asset catalog for LiveUpdateIcon.native images: created once, never
  // replaced (it holds your images).
  final catalog = File('${out.path}/Assets.xcassets/Contents.json');
  if (catalog.existsSync()) {
    stdout.writeln('keep   ${catalog.parent.path}');
  } else {
    catalog
      ..createSync(recursive: true)
      ..writeAsStringSync(_assetCatalogContents);
    stdout.writeln('write  ${catalog.parent.path}');
  }
  for (final MapEntry(key: file, value: content) in editable.entries) {
    final f = File('${out.path}/$file');
    if (f.existsSync() && !force) {
      stdout.writeln('keep   ${f.path} (yours to edit; --force replaces it)');
      continue;
    }
    f.writeAsStringSync(content);
    stdout.writeln('write  ${f.path}');
  }
  // A kept Info.plist (made before 0.4.0) gets the marker the plugin uses to
  // find its widget extension (see LiveUpdatesBridge.widgetExtensionRuns).
  final widgetPlist = '${out.path}/Info.plist';
  if (!_plistBuddy('Print :LiveUpdatesWidget', widgetPlist)) {
    if (_plistBuddy('Add :LiveUpdatesWidget bool true', widgetPlist)) {
      stdout.writeln('update $widgetPlist (LiveUpdatesWidget = true)');
    } else {
      stderr.writeln(
        'Could not add LiveUpdatesWidget to $widgetPlist; add it as a '
        'Boolean set to YES.',
      );
    }
  }

  if (editXcode) {
    if (!_enableLiveActivities('${ios.path}/Runner/Info.plist')) return 1;
    // Private temp directory (mkdtemp, 0700), removed afterwards.
    final tmp = Directory.systemTemp.createTempSync('live_updates_');
    final ProcessResult result;
    try {
      final script = File('${tmp.path}/add_target.rb')
        ..writeAsStringSync(render('add_target.rb.tmpl'));
      result = Process.runSync('ruby', [
        script.path,
        xcodeproj.path,
        name,
        out.path,
        appGroup ?? '',
      ]);
    } finally {
      tmp.deleteSync(recursive: true);
    }
    stdout.write(result.stdout);
    if (result.exitCode != 0) {
      stderr
        ..write(result.stderr)
        ..writeln(
          '\nCould not edit the Xcode project automatically (needs the '
          '"xcodeproj" Ruby gem, bundled with CocoaPods).\n'
          'Add the extension manually: Xcode > File > New > Target > Widget '
          'Extension named "$name" (deployment target 16.2), then replace its '
          'files with the ones in ${out.path}.',
        );
      return 1;
    }
  }
  if (appGroup != null) {
    stdout.writeln(
      '\nImages: register the App Group in your Apple Developer account if '
      'automatic signing does not, and keep it enabled for both targets.',
    );
  }
  stdout.writeln(
    '\nDone. Customize ${out.path}/${name}LiveActivity.swift to change the UI;\n'
    'run create_widget again after updating live_updates to refresh the\n'
    'LiveUpdates*.swift files (your layout is kept).',
  );
  return 0;
}

/// Text that every plugin-owned template contains.
const _generatedMarker = 'Generated by `dart run live_updates:create_widget`';

Future<Directory> _templatesDir() async {
  final uri = await Isolate.resolvePackageUri(
    Uri.parse('package:live_updates/src/cli/ios_widget/'),
  );
  if (uri == null) throw StateError('Cannot locate package:live_updates.');
  return Directory.fromUri(uri);
}

/// The widget needs the exact `LiveUpdatesAttributes` type the plugin uses,
/// so it is copied from the plugin sources instead of a template.
String _attributesSource(Directory templates) => File.fromUri(
  templates.uri.resolve(
    '../../../../ios/live_updates/Sources/live_updates/LiveUpdatesAttributes.swift',
  ),
).readAsStringSync();

/// Whether Ruby can load the `xcodeproj` gem; offers to install it for the
/// current user (no sudo) when it is missing and stdin is a terminal.
bool _ensureXcodeprojGem() {
  bool available() =>
      Process.runSync('ruby', ['-e', "require 'xcodeproj'"]).exitCode == 0;
  try {
    if (available()) return true;
  } on ProcessException {
    stderr.writeln('Ruby was not found. $_manualSteps');
    return false;
  }
  stderr.writeln(
    'The xcodeproj Ruby gem (used to add the widget target to Runner.xcodeproj) '
    'is not installed.',
  );
  if (stdin.hasTerminal) {
    stdout.write(
      'Install it for your user now with "gem install --user-install '
      'xcodeproj"? [y/N] ',
    );
    final answer = stdin.readLineSync()?.trim().toLowerCase();
    if (answer == 'y' || answer == 'yes') {
      final install = Process.runSync('gem', [
        'install',
        '--user-install',
        '--no-document',
        'xcodeproj',
        '--version',
        '~> 1.27',
      ]);
      stdout.write(install.stdout);
      stderr.write(install.stderr);
      if (install.exitCode == 0 && available()) return true;
      stderr.writeln('Installing the gem did not work.');
    }
  }
  stderr.writeln(
    'Install it with "gem install --user-install xcodeproj" (or install '
    'CocoaPods, which includes it) and run this command again. $_manualSteps',
  );
  return false;
}

const _manualSteps =
    'Alternatively run with --no-xcode and follow "Manual setup" in the '
    'live_updates README.';

/// Runs one PlistBuddy command; returns whether it succeeded.
bool _plistBuddy(String command, String plist) =>
    Process.runSync('/usr/libexec/PlistBuddy', [
      '-c',
      command,
      plist,
    ]).exitCode ==
    0;

/// Sets NSSupportsLiveActivities and the tap URL scheme. Returns `false`
/// (after printing why) if Info.plist could not be updated.
bool _enableLiveActivities(String plist) {
  if (!File(plist).existsSync()) {
    stderr.writeln('$plist not found.');
    return false;
  }
  if (!_registerTapScheme(plist)) return false;
  const key = 'NSSupportsLiveActivities';
  if (_plistBuddy('Print :$key', plist)) return true;
  if (!_plistBuddy('Add :$key bool true', plist)) {
    stderr.writeln('Could not set $key in $plist.');
    return false;
  }
  stdout.writeln('update $plist ($key = true)');
  return true;
}

/// Registers `liveupdates-<bundle id>` so widget taps reach the app.
bool _registerTapScheme(String plist) {
  const scheme = r'liveupdates-$(PRODUCT_BUNDLE_IDENTIFIER)';
  final dump = Process.runSync('/usr/libexec/PlistBuddy', [
    '-c',
    'Print :CFBundleURLTypes',
    plist,
  ]);
  if (dump.exitCode == 0 && (dump.stdout as String).contains(scheme)) {
    return true;
  }
  final commands = [
    if (dump.exitCode != 0) 'Add :CFBundleURLTypes array',
    'Add :CFBundleURLTypes:0 dict',
    'Add :CFBundleURLTypes:0:CFBundleURLName string live_updates',
    'Add :CFBundleURLTypes:0:CFBundleURLSchemes array',
    'Add :CFBundleURLTypes:0:CFBundleURLSchemes:0 string $scheme',
  ];
  for (final c in commands) {
    if (!_plistBuddy(c, plist)) {
      stderr.writeln('Could not register the URL scheme in $plist ("$c").');
      return false;
    }
  }
  stdout.writeln('update $plist (URL scheme $scheme)');
  return true;
}

/// `Contents.json` of an empty asset catalog, as Xcode writes it.
const _assetCatalogContents = '''{
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
''';
